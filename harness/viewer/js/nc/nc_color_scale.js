/**
 * Map a value to RGBA via a (vmin, vmax) linear scale + colormap LUT.
 * NaN / non-finite → fully transparent.
 */
export function valueToRGBA(value, vmin, vmax, lut) {
  if (!Number.isFinite(value)) return [0, 0, 0, 0];
  const span = vmax - vmin;
  let t;
  if (span <= 0) {
    t = 0.5;
  } else {
    t = (value - vmin) / span;
    if (t < 0) t = 0;
    if (t > 1) t = 1;
  }
  const idx = Math.round(t * 255);
  return [lut[idx * 3], lut[idx * 3 + 1], lut[idx * 3 + 2], 255];
}

/**
 * Resolve a (var-spec colormap) record to a concrete LUT + bounds.
 */
export function resolveColormap(colormap) {
  const lut = COLORMAPS[colormap?.name] || COLORMAPS.viridis;
  const vmin = Number.isFinite(colormap?.vmin) ? colormap.vmin : 0;
  const vmax = Number.isFinite(colormap?.vmax) ? colormap.vmax : 1;
  return { lut, vmin, vmax, name: colormap?.name || 'viridis' };
}

/**
 * Render a vertical colorbar onto a 2D canvas context.
 */
export function drawColorbar(ctx, { x, y, w, h }, scale, units = '') {
  const { lut, vmin, vmax } = scale;
  const img = ctx.createImageData(w, h);
  for (let py = 0; py < h; py++) {
    const t = 1 - py / (h - 1);
    const idx = Math.round(t * 255);
    const r = lut[idx * 3];
    const g = lut[idx * 3 + 1];
    const b = lut[idx * 3 + 2];
    for (let px = 0; px < w; px++) {
      const o = (py * w + px) * 4;
      img.data[o] = r;
      img.data[o + 1] = g;
      img.data[o + 2] = b;
      img.data[o + 3] = 255;
    }
  }
  ctx.putImageData(img, x, y);

  ctx.strokeStyle = 'rgba(255,255,255,0.55)';
  ctx.lineWidth = 1;
  ctx.strokeRect(x + 0.5, y + 0.5, w - 1, h - 1);

  ctx.fillStyle = 'rgba(255,255,255,0.92)';
  ctx.font = '11px ui-monospace, SFMono-Regular, Menlo, monospace';
  ctx.textAlign = 'left';
  ctx.textBaseline = 'top';
  ctx.fillText(formatNumber(vmax), x + w + 6, y - 2);
  ctx.textBaseline = 'bottom';
  ctx.fillText(formatNumber(vmin), x + w + 6, y + h + 2);
  if (units) {
    ctx.textBaseline = 'middle';
    ctx.fillText(units, x + w + 6, y + h / 2);
  }
}

function formatNumber(v) {
  if (!Number.isFinite(v)) return '—';
  const a = Math.abs(v);
  if (a !== 0 && (a < 0.01 || a >= 1e5)) return v.toExponential(2);
  if (a >= 100) return v.toFixed(1);
  if (a >= 1) return v.toFixed(2);
  return v.toFixed(3);
}
